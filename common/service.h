#pragma once

// The lifecycle every payload shares: one copy at a time (a newly sent copy
// replaces the running one), a web page with Logs and Settings tabs, a home
// screen tile, and a clean stop from the page or Payload Manager.

#include <signal.h>

#include "http.h"

typedef struct service_info {
  const char          *name;       // "fps60"; also names the log file
  const char          *version;    // "1.0.0", from the repository's VERSION
  const char          *proc_name;  // "fps60.elf", as process lists show it
  const char          *data_dir;   // "/data/fps60"
  int                  port;       // web page port
  const char          *tile_tid;   // home screen tile title ID
  const unsigned char *icon;       // tile icon and page logo (PNG)
  unsigned long        icon_size;
} service_info_t;

// Set by POST /api/quit or a stop signal.
extern volatile sig_atomic_t service_stop;

// Shared page assets, generated by tools/embed.py from common/ui.
extern const char common_ui_css[];
extern const char common_ui_js[];

// Opens the log, names the process and takes the web port, asking a running
// copy to quit first. Returns 0, or -1 when the port stays busy.
int  service_start(const service_info_t *info);

// Installs the tile (unless the user removed it) and announces the page.
void service_announce(void);

// Serves `handler` until a stop is requested, then exits the process.
void service_run(http_handler_t handler);

// Logs the stop and exits. Worker threads call it when service_stop is set.
void service_exit(void);

// Handles the routes every payload shares: /api/service, /api/logs,
// /<name>.log, /api/quit, /api/tile, /icon.png and /ui/common.{css,js}.
// Returns 1 if the request was handled.
int  service_handle(const http_req_t *req, http_resp_t *resp);

// For tests: sets up the state service_handle() uses without starting.
void service_setup(const service_info_t *info);

// Installs or removes the tile and remembers the choice. Returns 0 on
// success.
int  service_tile_set(int on);
