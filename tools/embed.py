#!/usr/bin/env python3
"""Embed files into C.

Usage: embed.py <output.c> <symbol>=<file> [<symbol>:bin=<file> ...]

<symbol>=<file> emits a NUL-terminated string `const char symbol[]`.
<symbol>:bin=<file> emits `const unsigned char symbol[]` plus
`const unsigned long symbol_size` for binary data such as images.
"""

import sys


def array(data):
    return ["  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out = ["/* Generated by tools/embed.py. Do not edit. */"]
    for arg in sys.argv[2:]:
        sym, path = arg.split("=", 1)
        binary = sym.endswith(":bin")
        sym = sym[:-4] if binary else sym
        with open(path, "rb") as f:
            data = f.read()
        if binary:
            out.append("const unsigned char %s[] = {" % sym)
            out.extend(array(data))
            out.append("};")
            out.append("const unsigned long %s_size = %d;" % (sym, len(data)))
            continue
        if b"\0" in data:
            sys.exit("%s contains NUL bytes; embed it with %s:bin=" % (path, sym))
        out.append("const char %s[] = {" % sym)
        out.extend(array(data))
        out.append("  0x00\n};")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
